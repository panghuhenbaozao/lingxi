    /// 基于光标前原始上下文（保留末尾数字与中文词尾）生成结构化上下文重排加分表。
    static func bonusMap(forContextBeforeCursor rawContext: String?) -> [String: Double] {
        guard let raw = rawContext, !raw.isEmpty else { return [:] }
        // 去掉末尾少量空白，保留数字与汉字
        var trimmed = raw
        while let last = trimmed.last, last == " " || last == "\t" {
            trimmed.removeLast()
        }
        guard let lastChar = trimmed.last else { return [:] }

        var out: [String: Double] = [:]

        // 1. 数字 + 量词/时间/货币消歧（如 `3` + `dian` -> `点`, `2026` + `nian` -> `年`）
        if lastChar.isASCII && lastChar.isNumber {
            var numChars: [Character] = []
            for ch in trimmed.reversed() {
                if ch.isASCII && ch.isNumber {
                    numChars.append(ch)
                    if numChars.count >= 6 { break }
                } else {
                    break
                }
            }
            let numStr = String(numChars.reversed())
            out = digitMeasureBonuses
            if let val = Int(numStr) {
                if (1900...2099).contains(val) {
                    out["年"] = 5.4
                } else if (1...12).contains(val) {
                    out["点"] = 4.9
                    out["月"] = 4.6
                } else if (13...24).contains(val) {
                    out["点"] = 4.7
                    out["号"] = 4.4
                    out["日"] = 4.3
                } else if (25...31).contains(val) {
                    out["号"] = 4.5
                    out["日"] = 4.4
                }
            }
            return out
        }

        // 2. 中文短语/动词/前缀上下文消歧（优先 4/2 字精确匹配，再退化至 1 字触发）
        for len in [4, 2, 1] {
            if trimmed.count >= len {
                let tail = String(trimmed.suffix(len))
                if let bonuses = prefixPhraseBonuses[tail] {
                    for (k, v) in bonuses {
                        out[k] = max(out[k] ?? 0, v)
                    }
                    if len >= 2 { break }
                }
            }
        }
        return out
    }
